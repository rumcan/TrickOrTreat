import fs from 'node:fs/promises';
import sharp from 'sharp';
// The reference town, traced by hand, turned into the game's tiles.
//   art/town/static/ground/trace/trace.json   roads, landmarks and homes in PIXELS of town-reference.png
//   node scripts/town-trace.mjs               -> check-<n>.png  the trace drawn back on the reference (to proof-read it)
//                                             -> src/game/town-trace.json  the same trace in tile coordinates
// The picture's four corners (top, right, bottom, left: where its straight edges would meet, the picture itself is
// cropped and rounded there) are tiles (0,0) (94,0) (94,94) (0,94).
const DIR='art/town/static/ground/trace',N=94,W=1672,H=941;
const trace=JSON.parse(await fs.readFile(`${DIR}/trace.json`,'utf8'));
function homography(src,dst){
 const A=[],B=[];
 for(let k=0;k<4;k++){const [x,y]=src[k],[X,Y]=dst[k];A.push([x,y,1,0,0,0,-x*X,-y*X]);B.push(X);A.push([0,0,0,x,y,1,-x*Y,-y*Y]);B.push(Y);}
 for(let c=0;c<8;c++){let p=c;for(let r=c+1;r<8;r++)if(Math.abs(A[r][c])>Math.abs(A[p][c]))p=r;[A[c],A[p]]=[A[p],A[c]];[B[c],B[p]]=[B[p],B[c]];
  for(let r=0;r<8;r++)if(r!==c){const f=A[r][c]/A[c][c];for(let k=c;k<8;k++)A[r][k]-=f*A[c][k];B[r]-=f*B[c];}}
 const h=B.map((v,i)=>v/A[i][i]);
 return (x,y)=>{const w=h[6]*x+h[7]*y+1;return [(h[0]*x+h[1]*y+h[2])/w,(h[3]*x+h[4]*y+h[5])/w];};
}
const SQUARE=[[0,0],[N,0],[N,N],[0,N]];
const rawPixel=homography(SQUARE,trace.corners),toTile=homography(trace.corners,SQUARE);
const toPixel=(x,y)=>rawPixel((x-(trace.inset??0))*N/(N-2*(trace.inset??0)),(y-(trace.inset??0))*N/(N-2*(trace.inset??0)));
// the picture runs to its very edge; the game keeps a wooded margin of 'inset' tiles around the same layout
const inset=trace.inset??0,fit=v=>inset+v*(N-2*inset)/N;
const tile=p=>toTile(...p).map(v=>Math.round(fit(v)*10)/10);

// proof sheet: grid + trace over the reference
let svg=`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">`;
const seg=(a,b,c,w)=>{const [x1,y1]=toPixel(...a),[x2,y2]=toPixel(...b);svg+=`<line x1="${x1.toFixed(1)}" y1="${y1.toFixed(1)}" x2="${x2.toFixed(1)}" y2="${y2.toFixed(1)}" stroke="${c}" stroke-width="${w}"/>`;};
for(let k=0;k<=N;k+=2){const major=k%10===0;if(!major&&!process.env.FINE)continue;seg([k,0],[k,N],'#00ffff66',.6);seg([0,k],[N,k],'#ffe60066',.6);}
for(let x=0;x<=N;x+=10)for(let y=0;y<=N;y+=10){const [px,py]=toPixel(x,y);svg+=`<text x="${(px+2).toFixed(1)}" y="${(py-1.5).toFixed(1)}" fill="#fff" stroke="#000" stroke-width=".3" font-size="7" font-family="monospace">${x},${y}</text>`;}
for(const [name,points]of Object.entries(trace.roads)){
 svg+=`<polyline points="${points.map(p=>p.join(',')).join(' ')}" fill="none" stroke="#ff2bd6" stroke-width="1.6" stroke-linejoin="round"/>`;
 for(const [x,y]of points)svg+=`<circle cx="${x}" cy="${y}" r="1.6" fill="#fff"/>`;
 svg+=`<text x="${points[0][0]+3}" y="${points[0][1]-3}" fill="#ff9cf0" stroke="#000" stroke-width=".25" font-size="6.5" font-family="monospace">${name}</text>`;
}
for(const [name,value]of Object.entries(trace.marks)){
 const points=Array.isArray(value[0])?value:[value];
 if(points.length>1)svg+=`<polygon points="${points.map(p=>p.join(',')).join(' ')}" fill="#35ff7a22" stroke="#35ff7a" stroke-width="1"/>`;
 else svg+=`<circle cx="${points[0][0]}" cy="${points[0][1]}" r="3" fill="none" stroke="#35ff7a" stroke-width="1.2"/>`;
 svg+=`<text x="${points[0][0]+4}" y="${points[0][1]+2}" fill="#9dffbd" stroke="#000" stroke-width=".25" font-size="6.5" font-family="monospace">${name}</text>`;
}
for(const [i,[x,y]]of trace.homes.entries())svg+=`<rect x="${x-3}" y="${y-3}" width="6" height="6" fill="none" stroke="#ffb02b" stroke-width="1.2"/><text x="${x+4}" y="${y+2}" fill="#ffd08a" stroke="#000" stroke-width=".25" font-size="6" font-family="monospace">h${i}</text>`;
svg+='</svg>';
const sheet=await sharp(`${DIR}/town-reference.png`).composite([{input:Buffer.from(svg)}]).png().toBuffer();
await sharp(sheet).toFile(`${DIR}/check-full.png`);
const cw=640,ch=400,cols=[0,516,1032],rows=[0,270,541];let n=0;
for(const top of rows)for(const left of cols)await sharp(sheet).extract({left,top,width:cw,height:ch}).resize({width:1900,kernel:'lanczos3'}).png().toFile(`${DIR}/check-${n++}.png`);

const tiles={note:'Generated by scripts/town-trace.mjs from the hand trace of the reference town. Tile coordinates.',
 roads:Object.fromEntries(Object.entries(trace.roads).map(([k,v])=>[k,v.map(tile)])),
 marks:Object.fromEntries(Object.entries(trace.marks).map(([k,v])=>[k,Array.isArray(v[0])?v.map(tile):tile(v)])),
 homes:trace.homes.map(tile)};
const json=JSON.stringify(tiles).replace(/"(roads|marks|homes)":/g,'\n "$1":').replace(/\],"/g,'],\n  "').replace(/\}$/,'\n}\n');
await fs.writeFile('src/game/town-trace.json',json);
if(process.argv.includes('--print'))console.log(json);
// a point from a zoomed proof section, in pixels of the reference:  node scripts/town-trace.mjs --at <section> u,v ...
const at=process.argv.indexOf('--at');
if(at>0){const s=Number(process.argv[at+1]);console.log(process.argv.slice(at+2).map(p=>{const [u,v]=p.split(',').map(Number);return `[${Math.round(cols[s%3]+u*cw/1900)},${Math.round(rows[Math.floor(s/3)]+v*cw/1900)}]`;}).join(','));}
// pixels of the reference -> tiles:  node scripts/town-trace.mjs --px x,y ...
const px=process.argv.indexOf('--px');
if(px>0)console.log(process.argv.slice(px+1).map(p=>tile(p.split(',').map(Number)).join(',')).join('  '));
